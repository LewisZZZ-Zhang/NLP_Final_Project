"""Final high-noise-recall frontier; no minimum clean-retention constraint."""
import argparse,hashlib,json,time,sys
from pathlib import Path
import numpy as np
from logistic_experiment import ROOT,CS,fit_pipeline,export_model,predict,log_loss
from logistic_filter import apply_model
from simple_ablation import fold_id,write_json,write_rows
from retest import score,metrics,load_dataset
from bag_rejection import summary,no_lexical_evidence

TARGETS=[.90,.95,.99]
CACHE=ROOT/'results/logistic_20261014'

def decisions(rows,values,kind,thresholds):
 out=[]
 for r,v in zip(rows,values):
  t=thresholds['NA' if r['relation']=='NA' else 'non-NA']
  keep=float(v)<t if kind=='logistic' else float(v)>=t
  out.append(dict(r,selection_score=float(v),selection_kind=kind,threshold=t,keep=keep))
 return out

def select_threshold(rows,values,kind,group,target):
 subset=[(r,float(v)) for r,v in zip(rows,values) if (r['relation']=='NA')==(group=='NA')]
 grid=([i/100 for i in range(101)]+[1.000001]) if kind=='logistic' else [i/100 for i in range(152)]
 best=None;curve=[]
 for t in grid:
  pred=decisions([r for r,v in subset],[v for r,v in subset],kind,{group:t});m=metrics(pred)
  feasible=m['recall'] is not None and m['recall']>=target
  curve.append(dict(threshold=t,metrics=m,feasible=feasible))
  if feasible:
   key=(m['clean_retention'],m['purity'] if m['purity'] is not None else -1,-m['deletion_rate'],t if kind=='logistic' else -t)
   if best is None or key>best[0]:best=(key,t,m)
 if best is None:raise RuntimeError('Drop-all should be feasible if noise labels exist')
 return dict(threshold=best[1],metrics=best[2],curve=curve)

def tune_lr(rows,label,target,out):
 candidates=[];best=None
 for C in CS:
  cachefile=CACHE/f'{label}_C{C}_inner_predictions.jsonl'
  cache={r['instance_id']:r for r in map(json.loads,cachefile.read_text().splitlines())}
  assert set(cache)=={r['instance_id'] for r in rows}
  # These inner scores were generated by exactly the same scaler/model fitting
  # procedure; only the decision objective changes, not the trained inner fits.
  values=[cache[r['instance_id']]['noise_score'] for r in rows]
  for r in rows:assert cache[r['instance_id']]['inner_fold']==fold_id(r['sentence_text_id'])
  choices={g:select_threshold(rows,values,'logistic',g,target) for g in ['NA','non-NA']}
  m=choices['non-NA']['metrics'];loss=float(log_loss([r['is_noise'] for r in rows],values,labels=[False,True]))
  entry=dict(C=C,choices=choices,thresholds={g:x['threshold'] for g,x in choices.items()},inner_log_loss=loss,cache_sha256=hashlib.sha256(cachefile.read_bytes()).hexdigest())
  candidates.append(entry);key=(m['clean_retention'],m['purity'] if m['purity'] is not None else -1,-loss,-C)
  if best is None or key>best[0]:best=(key,entry)
 write_json(out/f'{label}_target{int(target*100)}_tuning.json',candidates)
 return best[1]

def tune_rule(rows,target):
 choices={g:select_threshold(rows,[r['raw_score'] for r in rows],'raw',g,target) for g in ['NA','non-NA']}
 return dict(thresholds={g:c['threshold'] for g,c in choices.items()},choices=choices)

def run(out):
 out.mkdir(parents=True,exist_ok=False)
 protocol=dict(targets=TARGETS,meaning='noise recall goals, not clean-retention targets or classifier cutoffs',objective='Within each NA/non-NA group maximize retained clean fraction subject to fitted noise recall >= target; no minimum clean retention, no min_keep, no class coverage constraint',
               selection='For LR, select C maximizing non-NA clean retention then non-NA purity then lower inner log loss then smaller C. Group thresholds selected separately. Report all targets; no single winner or test-driven choice.',
               validation='reuse audited inner OOF predictions from prior LR training (unchanged features/training); reselect C/cutoffs only on outer train inner predictions; refit selected C on outer train; same sentence outer folds; full-dev configuration frozen before diagnostic tests',
               baselines=['raw threshold with min_keep=0','keep-all','drop-all'],limitations='Exploratory reuse of previously inspected dev/test. No new pristine test. High recall can sacrifice almost all clean data.',
               source_hashes={str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in [ROOT/'scripts/recall_frontier.py',ROOT/'filter/model.py',ROOT/'scripts/logistic_experiment.py',CACHE/'protocol.json',CACHE/'verification.json']})
 write_json(out/'protocol.json',protocol);rows=score(load_dataset(ROOT/'data/arnor_benchmark_v2/arnor_dev.txt')[0]);results={};configs={}
 for target in TARGETS:
  key=str(int(target*100));ooflr=[];oofraw=[];folds=[]
  for f in range(5):
   train=[r for r in rows if fold_id(r['sentence_text_id'])!=f];val=[r for r in rows if fold_id(r['sentence_text_id'])==f]
   tuned=tune_lr(train,f'outer{f}',target,out);pipe=fit_pipeline(train,tuned['C']);model=export_model(pipe,tuned['C'],tuned['thresholds'])
   lr=[dict(r,fold=f) for r in decisions(val,predict(pipe,val),'logistic',model['thresholds'])]
   rule=tune_rule(train,target);raw=[dict(r,fold=f) for r in decisions(val,[r['raw_score'] for r in val],'raw',rule['thresholds'])]
   # Evaluation-batch bag sizes for diagnostics only; neither selector uses bags.
   sizes={}
   for r in val:sizes[r['bag_id']]=sizes.get(r['bag_id'],0)+1
   for r in lr+raw:r['bag_size']=sizes[r['bag_id']]
   ooflr+=lr;oofraw+=raw;folds.append(dict(fold=f,model=model,raw_thresholds=rule['thresholds'],logistic=summary(lr),raw=summary(raw)))
  assert len(ooflr)==len(rows) and len({r['instance_id'] for r in ooflr})==len(rows)
  write_rows(out/f'oof_logistic_{key}.jsonl',ooflr);write_rows(out/f'oof_raw_{key}.jsonl',oofraw);write_json(out/f'outer_{key}.json',folds)
  tuned=tune_lr(rows,'final',target,out);pipe=fit_pipeline(rows,tuned['C']);model=export_model(pipe,tuned['C'],tuned['thresholds']);rawcfg=tune_rule(rows,target)
  configs[key]=dict(logistic=model,raw=rawcfg);write_json(out/f'model_recall{key}.json',model)
  results[key]=dict(oof_logistic=summary(ooflr),oof_raw=summary(oofraw))
  print('target',target,'OOF non-NA',results[key]['oof_logistic']['non-NA'],flush=True)
 write_json(out/'frozen_configs.json',configs)
 for split in ['dev','test','test_noise']:
  rs=rows if split=='dev' else score(load_dataset(ROOT/f'data/arnor_benchmark_v2/arnor_{split}.txt')[0])
  write_json(out/f'{split}_baselines.json',{n:summary([dict(r,keep=k) for r in rs]) for n,k in [('keep_all',True),('drop_all',False)]})
  for key,c in configs.items():
   lr=apply_model(rs,c['logistic']);lr=[dict(r,selection_score=r['noise_score']) for r in lr]
   raw=decisions(rs,[r['raw_score'] for r in rs],'raw',c['raw']['thresholds'])
   results[key][split+'_logistic']=summary(lr);results[key][split+'_raw']=summary(raw)
   write_rows(out/f'{split}_logistic_{key}.jsonl',lr);write_rows(out/f'{split}_raw_{key}.jsonl',raw)
   if split!='dev':
    seen={r['sentence_text_id'] for r in rows};unseen=[r for r in rs if r['sentence_text_id'] not in seen]
    results[key][split+'_logistic_no_dev_text']=summary(apply_model(unseen,c['logistic']))
 write_json(out/'results.json',results)
 # Limit of no-evidence guard irrespective of raw threshold; descriptive only.
 write_json(out/'guard_recall_ceiling_dev.json',dict(non_NA_noise=sum(r['is_noise'] is True and r['relation']!='NA' for r in rows),eligible_noise=sum(r['is_noise'] is True and r['relation']!='NA' and no_lexical_evidence(r) for r in rows)))
 print('Finished; no target automatically promoted.',flush=True)

if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--out',type=Path,default=ROOT/'results/recall_frontier_20261014');a=p.parse_args();run(a.out)
